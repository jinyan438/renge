export type PocketPromptId = typeof POCKET_PROMPTS[number]["id"];
export type PocketPromptOverrides = Partial<Record<PocketPromptId, string>>;

export function normalizePocketPromptOverrides(value: unknown): PocketPromptOverrides {
  if (!value || typeof value !== "object" || Array.isArray(value)) return {};
  const entries = value as Record<string, unknown>;
  return Object.fromEntries(POCKET_PROMPTS.flatMap(prompt => {
    const text = entries[prompt.id];
    return typeof text === "string" && text.trim() && text.length <= 50000 && text !== prompt.defaultText ? [[prompt.id, text]] : [];
  }));
}

export function renderPocketPrompt(id: PocketPromptId, overrides?: PocketPromptOverrides, variables: Record<string, string | number> = {}): string {
  const definition = POCKET_PROMPTS.find(prompt => prompt.id === id)!;
  const template = overrides?.[id]?.trim() ? overrides[id]! : definition.defaultText;
  // One pass prevents quoted records and user text from being treated as templates.
  return template.replace(/\{\{([a-zA-Z][a-zA-Z0-9]*)\}\}/g, (token, key: string) => Object.hasOwn(variables, key) ? String(variables[key]) : token);
}
